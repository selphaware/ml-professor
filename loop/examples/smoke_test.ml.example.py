"""Example gate for a modelling tool, built on gatekit. Copy the SHAPE, not the checks.

Project: a small "predictability profiler", `app/profiler.py`, exposing

    profile(csv_path, target, seed=0) -> {
        "n_rows": int, "baseline": float, "score": float, "lift": float,
        "leakage": [column names flagged as leaking the target]}

Gate argument (the deliverable): the `app` folder.

A modelling tool has no "right answer" on real data, so this gate never
asserts a score on real data. It manufactures ground truth instead: synthetic
datasets where the correct conclusion is known by construction.

  signal.csv   target driven by one feature      -> lift must be clearly positive
  noise.csv    target is a coin flip             -> lift must be about zero
  leak.csv     a column is a copy of the target  -> the tool must flag it
  gaps.csv     some cells are blank              -> every row must still be counted

Named silent failures:
  F1  the score is computed on rows the model was fitted on
  F2  a leaked column is used as a feature and nothing is flagged
  F3  rows with missing values are dropped without being reported
  F4  the model is never really fitted; the score is just the baseline

The patterns shown here, all of which matter for any stochastic deliverable:
  * every dataset is generated by the gate from a fixed seed (deterministic)
  * scores are asserted as BANDS (ctx.require_between), never exact values
  * the heavy check is marked slow=True, so it is skipped on each edit and run
    when a builder finishes; setup reads ctx.fast to skip its preparation too
  * --selftest runs the good fixture twice and fails if any recorded value moves

Standard library only, so the example runs anywhere. A real gate would import
the project's own stack through the deliverable, never reimplement it.
"""
import csv
import importlib.util
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gatekit import Gate  # noqa: E402

gate = Gate("predictability-profiler")

TARGET = "churned"


# ------------------------------------------------- synthetic ground truth --

def _write(path: Path, header, rows) -> None:
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.writer(fh)
        writer.writerow(header)
        writer.writerows(rows)


def make_signal(path: Path, n=300, seed=11, leak=False, gaps=False) -> int:
    """Target is decided by x1; x2 and x3 are noise. Returns the row count."""
    rng = random.Random(seed)
    header = ["x1", "x2", "x3"] + (["outcome_copy"] if leak else []) + [TARGET]
    rows = []
    for i in range(n):
        x1, x2, x3 = rng.gauss(0, 1), rng.gauss(0, 1), rng.gauss(0, 1)
        y = 1 if x1 > 0 else 0
        row = [f"{x1:.4f}", f"{x2:.4f}", f"{x3:.4f}"]
        if gaps and i % 10 == 0:
            row[2] = ""                       # a blank cell, not a missing row
        rows.append(row + ([y] if leak else []) + [y])
    _write(path, header, rows)
    return n


def make_noise(path: Path, n=240, seed=23) -> int:
    """Target is a coin flip: nothing here can be predicted."""
    rng = random.Random(seed)
    rows = [[f"{rng.gauss(0, 1):.4f}" for _ in range(4)] + [rng.randint(0, 1)]
            for _ in range(n)]
    _write(path, ["x1", "x2", "x3", "x4", TARGET], rows)
    return n


@gate.setup
def prepare(ctx):
    data = ctx.artifacts / "ml_fixtures"          # the only place a gate may write
    data.mkdir(parents=True, exist_ok=True)
    ctx.state["signal"] = data / "signal.csv"
    ctx.state["leak"] = data / "leak.csv"
    ctx.state["gaps"] = data / "gaps.csv"
    make_signal(ctx.state["signal"])
    make_signal(ctx.state["leak"], leak=True)
    ctx.state["gaps_rows"] = make_signal(ctx.state["gaps"], gaps=True)
    if not ctx.fast:                              # heavy preparation: full run only
        ctx.state["noise"] = data / "noise.csv"
        make_noise(ctx.state["noise"])
    spec = importlib.util.spec_from_file_location("profiler_under_test",
                                                  ctx.deliverable / "profiler.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    ctx.state["profile"] = module.profile


# ------------------------------------------------------------------ checks --

@gate.check("rows.reconcile", catches=["F3"],
            doc="n_rows equals the number of data lines, blanks included")
def rows_reconcile(ctx):
    got = ctx.state["profile"](ctx.state["gaps"], TARGET)["n_rows"]
    want = ctx.state["gaps_rows"]
    ctx.require(got == want,
                f"profile() counted {got} rows, the file has {want}: rows with blank "
                "cells are being dropped without being reported")


@gate.check("signal.detected", catches=["F4"],
            doc="clear positive lift when the target is driven by a feature")
def signal_detected(ctx):
    result = ctx.state["profile"](ctx.state["signal"], TARGET)
    # Band measured on the good fixture, with margin. Never an exact value.
    ctx.require_between(result["lift"], 0.25, 0.55, "lift on the planted-signal data")


@gate.check("leak.flagged", catches=["F2"],
            doc="a column that copies the target is flagged, not used")
def leak_flagged(ctx):
    result = ctx.state["profile"](ctx.state["leak"], TARGET)
    ctx.require("outcome_copy" in result["leakage"],
                f"'outcome_copy' is identical to the target and was not flagged "
                f"(leakage={result['leakage']}, score={result['score']:.3f}): a perfect "
                "score from a leaked column is being reported as predictability")


@gate.check("noise.no_signal", catches=["F1"], slow=True,
            doc="lift is about zero when the target is a coin flip")
def noise_no_signal(ctx):
    result = ctx.state["profile"](ctx.state["noise"], TARGET)
    ctx.require_between(result["lift"], -0.20, 0.20, "lift on the pure-noise data")


# ---------------------------------------------------------------- fixtures --

GOOD = '''
import csv
import random


def _num(value):
    try:
        return float(value)
    except (TypeError, ValueError):
        return 0.0                      # impute a blank; never drop the row


def profile(csv_path, target, seed=0):
    with open(csv_path, newline="", encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh)]
    y = [int(float(r[target])) for r in rows]
    features = [c for c in rows[0] if c != target]
    X = {f: [_num(r[f]) for r in rows] for f in features}
    leakage = [f for f in features if all(int(v) == t for v, t in zip(X[f], y))]
    features = [f for f in features if f not in leakage]

    order = list(range(len(rows)))
    random.Random(seed).shuffle(order)
    cut = int(len(order) * 0.7)
    train, test = order[:cut], order[cut:]

    def predict(i):                     # 1-nearest-neighbour, fitted on train only
        nearest = min((j for j in train if j != i),
                      key=lambda j: sum((X[f][i] - X[f][j]) ** 2 for f in features))
        return y[nearest]

    majority = 1 if sum(y[i] for i in train) * 2 >= len(train) else 0
    scored = test
    score = sum(predict(i) == y[i] for i in scored) / len(scored)
    baseline = sum(y[i] == majority for i in scored) / len(scored)
    return {"n_rows": len(rows), "baseline": baseline, "score": score,
            "lift": score - baseline, "leakage": leakage}
'''

BROKEN = {
    # F1: the classic. Scoring on the training rows; 1-NN memorises them.
    "F1": GOOD.replace("min((j for j in train if j != i),", "min((j for j in train),")
              .replace("scored = test", "scored = train"),
    # F2: the leak check is gone and the leaked column stays a feature.
    "F2": GOOD.replace(
        "leakage = [f for f in features if all(int(v) == t for v, t in zip(X[f], y))]",
        "leakage = []"),
    # F3: rows with a blank cell vanish before anyone counts them.
    "F3": GOOD.replace("rows = [r for r in csv.DictReader(fh)]",
                       "rows = [r for r in csv.DictReader(fh) if all(v != '' for v in r.values())]"),
    # F4: nothing is fitted; every prediction is the majority class.
    "F4": GOOD.replace("return y[nearest]", "return majority"),
}


def _deliverable(tmp: Path, source: str) -> Path:
    (tmp / "app").mkdir(parents=True, exist_ok=True)
    (tmp / "app" / "profiler.py").write_text(source, encoding="utf-8")
    return tmp / "app"


@gate.good_fixture
def good(tmp):
    return _deliverable(tmp, GOOD)


@gate.failure_mode("F1", "score computed on rows the model was fitted on")
def broken_train_scoring(tmp):
    return _deliverable(tmp, BROKEN["F1"])


@gate.failure_mode("F2", "leaked column used as a feature, nothing flagged")
def broken_leak_unflagged(tmp):
    return _deliverable(tmp, BROKEN["F2"])


@gate.failure_mode("F3", "rows with missing values dropped without being reported")
def broken_rows_dropped(tmp):
    return _deliverable(tmp, BROKEN["F3"])


@gate.failure_mode("F4", "model never fitted; score is just the baseline")
def broken_never_fitted(tmp):
    return _deliverable(tmp, BROKEN["F4"])


if __name__ == "__main__":
    gate.main()
